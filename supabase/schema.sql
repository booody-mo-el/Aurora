  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('admin','moderator')),
  created_at timestamptz not null default now()
);

alter table public.admin_roles enable row level security;
revoke all on public.admin_roles from anon, public;
grant select on public.admin_roles to authenticated;

drop policy if exists "Users check own admin role" on public.admin_roles;
create policy "Users check own admin role"
  on public.admin_roles for select to authenticated
  using (auth.uid() = user_id);

create table if not exists public.curated_sources (
  id text primary key,
  tmdb_id integer,
  title text not null,
  year integer not null,
  description text not null,
  item_url text not null,
  video_url text not null,
  stream_type text not null default 'mp4' check (stream_type in ('mp4','hls','embed')),
  provider text not null,
  rights_label text not null,
  rights_url text not null,
  rights_note text not null,
  attribution text not null,
  runtime_seconds integer not null check (runtime_seconds > 0),
  content_type text not null default 'feature' check (content_type in ('feature','short')),
  poster_path text,
  subtitles jsonb not null default '[]'::jsonb,
  featured boolean not null default false,
  active boolean not null default true,
  fallback_urls jsonb not null default '[]'::jsonb,
  quality_sources jsonb not null default '[]'::jsonb,
  completeness text not null default 'complete' check (completeness in ('complete','incomplete')),
  source_verified boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.curated_sources enable row level security;
revoke all on public.curated_sources from anon, public;
grant select on public.curated_sources to anon, authenticated;
grant insert, update, delete on public.curated_sources to authenticated;

drop policy if exists "Anyone can read active curated sources" on public.curated_sources;
drop policy if exists "Admins manage curated sources" on public.curated_sources;
create policy "Anyone can read active curated sources"
  on public.curated_sources for select to anon, authenticated
  using (active = true or exists (select 1 from public.admin_roles ar where ar.user_id = auth.uid() and ar.role = 'admin'));
create policy "Admins manage curated sources"
  on public.curated_sources for all to authenticated
  using (exists (select 1 from public.admin_roles ar where ar.user_id = auth.uid() and ar.role = 'admin'))
  with check (exists (select 1 from public.admin_roles ar where ar.user_id = auth.uid() and ar.role = 'admin'));

create table if not exists public.content_reports (
  id bigint generated by default as identity primary key,
  reporter_id uuid references auth.users(id) on delete set null,
  reporter_label text not null default 'guest',
  target_type text not null check (target_type in ('title','review','source')),
  target_id text not null,
  reason text not null check (char_length(trim(reason)) between 3 and 500),
  status text not null default 'open' check (status in ('open','resolved','dismissed')),
  created_at timestamptz not null default now()
);

alter table public.content_reports enable row level security;
revoke all on public.content_reports from anon, public;
grant select, insert, update on public.content_reports to authenticated;

drop policy if exists "Users submit reports" on public.content_reports;
drop policy if exists "Admins read and update reports" on public.content_reports;
drop policy if exists "Admins update reports" on public.content_reports;
create policy "Users submit reports"
  on public.content_reports for insert to authenticated
  with check (auth.uid() = reporter_id);
create policy "Admins read and update reports"
  on public.content_reports for select to authenticated
  using (auth.uid() = reporter_id or exists (select 1 from public.admin_roles ar where ar.user_id = auth.uid() and ar.role in ('admin','moderator')));
create policy "Admins update reports"
  on public.content_reports for update to authenticated
  using (exists (select 1 from public.admin_roles ar where ar.user_id = auth.uid() and ar.role in ('admin','moderator')))
  with check (exists (select 1 from public.admin_roles ar where ar.user_id = auth.uid() and ar.role in ('admin','moderator')));

