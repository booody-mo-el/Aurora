-- Apply in Supabase Dashboard → SQL Editor.
-- Aurora uses Supabase Auth magic links and stores only each user's own saved titles.
create table if not exists public.saved_titles (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  media_type text not null check (media_type in ('movie','tv')),
  tmdb_id integer not null,
  title text not null,
  poster_path text,
  vote_average numeric,
  created_at timestamptz not null default now(),
  unique(user_id, media_type, tmdb_id)
);

create index if not exists saved_titles_user_created_idx
  on public.saved_titles (user_id, created_at desc);

alter table public.saved_titles enable row level security;
revoke all on public.saved_titles from anon, public;
grant select, insert, delete on public.saved_titles to authenticated;

drop policy if exists "Users read own saved titles" on public.saved_titles;
drop policy if exists "Users add own saved titles" on public.saved_titles;
drop policy if exists "Users delete own saved titles" on public.saved_titles;
create policy "Users read own saved titles"
  on public.saved_titles for select to authenticated
  using (auth.uid() = user_id);
create policy "Users add own saved titles"
  on public.saved_titles for insert to authenticated
  with check (auth.uid() = user_id);
create policy "Users delete own saved titles"
  on public.saved_titles for delete to authenticated
  using (auth.uid() = user_id);


-- Public ratings/comments per title; authenticated users may only manage their own review.
create table if not exists public.title_reviews (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  media_type text not null check (media_type in ('movie','tv')),
  tmdb_id integer not null,
  title text not null,
  rating integer not null check (rating between 1 and 10),
  comment text not null check (char_length(trim(comment)) between 1 and 2000),
  created_at timestamptz not null default now(),
  unique(user_id, media_type, tmdb_id)
);

create index if not exists title_reviews_title_created_idx
  on public.title_reviews (media_type, tmdb_id, created_at desc);

alter table public.title_reviews enable row level security;
revoke all on public.title_reviews from anon, public;
grant select on public.title_reviews to anon, authenticated;
grant insert, update, delete on public.title_reviews to authenticated;

drop policy if exists "Anyone can read title reviews" on public.title_reviews;
drop policy if exists "Users add own title reviews" on public.title_reviews;
drop policy if exists "Users update own title reviews" on public.title_reviews;
drop policy if exists "Users delete own title reviews" on public.title_reviews;
create policy "Anyone can read title reviews"
  on public.title_reviews for select to anon, authenticated
  using (true);
create policy "Users add own title reviews"
  on public.title_reviews for insert to authenticated
  with check (auth.uid() = user_id);
create policy "Users update own title reviews"
  on public.title_reviews for update to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);
create policy "Users delete own title reviews"
  on public.title_reviews for delete to authenticated
  using (auth.uid() = user_id);
