-- Apply this in Supabase SQL Editor to enable per-user saved titles.
create table if not exists public.saved_titles (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  media_type text not null check (media_type in ('movie','tv')),
  tmdb_id integer not null,
  title text not null,
  poster_path text,
  vote_average numeric,
  created_at timestamptz not null default now(),
  unique(user_id, media_type, tmdb_id)
);
alter table public.saved_titles enable row level security;
create policy "Users read own saved titles" on public.saved_titles for select to authenticated using (auth.uid()=user_id);
create policy "Users add own saved titles" on public.saved_titles for insert to authenticated with check (auth.uid()=user_id);
create policy "Users delete own saved titles" on public.saved_titles for delete to authenticated using (auth.uid()=user_id);
